export const messages: Record<Locale, Messages> = { en, id }

export type TranslateParams = Record<string, string | number>
export type Translate = (key: MessageKey, params?: TranslateParams) => string

/** Picks a supported locale from a BCP 47 tag such as "id-ID" or "en-US". */
export function resolveLocale(tag: string | null | undefined): Locale {
  const lang = (tag ?? '').toLowerCase().split(/[-_]/)[0]
  // "in" is the legacy ISO 639 code for Indonesian that some systems still report.
  return lang === 'id' || lang === 'in' ? 'id' : 'en'
}

export function createTranslator(locale: Locale): Translate {
  const table = messages[locale]
  return (key, params) => {
    const template = table[key] ?? messages.en[key] ?? key
    if (!params) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match
    )
  }
}
